export type Ui = typeof ui;

/** Interpolate `{var}` placeholders in a copy template. */
export function tpl(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(vars[key] ?? "")
  );
}

/**
 * Typed copy lookup. Referencing an unknown key is a compile error.
 * Falls back to the English mirror only if the Spanish value were ever empty,
 * so a label never renders empty.
 */
export function copy<N extends keyof Ui, K extends keyof Ui[N]>(
  namespace: N,
  key: K
): Ui[N][K] {
  const value = ui[namespace][key];
  if (typeof value === "string" && value.length === 0) {
    const enNamespace = en[namespace as keyof typeof en];
    const fallback = enNamespace ? (enNamespace as Record<string, unknown>)[key as string] : undefined;
    return (typeof fallback === "string" ? fallback : value) as Ui[N][K];
  }
  return value;
}
